using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Globalization;
using System.Text;

namespace Caprine.Durations.Generators;

internal static class DurationEmitter
{
    internal static string Emit(ISymbol                     member,
                                MemberDeclarationSyntax     declaration,
                                List<TypeDeclarationSyntax> containers,
                                DurationSignature           signature,
                                ParsedDuration              duration)
    {
        var builder = new StringBuilder("// <auto-generated/>\n#nullable enable\n");

        var indentation = 0;
        var namespaces  = new Stack<string>();
        for (var current = member.ContainingNamespace; !current.IsGlobalNamespace; current = current.ContainingNamespace)
        {
            namespaces.Push("@" + current.Name);
        }

        if (namespaces.Count != 0)
        {
            builder.Append("namespace ").Append(string.Join(".", namespaces)).AppendLine();
            builder.AppendLine("{");
            indentation = 4;
        }

        for (var index = containers.Count - 1; index >= 0; index--)
        {
            var container = containers[index];
            var kind = container is RecordDeclarationSyntax record
                ? record.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword) ? "record struct" : "record class"
                : container.Keyword.Text;
            builder.Append(' ', indentation).Append(string.Join(" ", container.Modifiers.Select(modifier => modifier.Text)));
            builder.Append(' ').Append(kind).Append(" @").Append(container.Identifier.ValueText);

            if (container.TypeParameterList is { } typeParameters)
            {
                builder.Append('<').Append(string.Join(", ", typeParameters.Parameters.Select(parameter => "@" + parameter.Identifier.ValueText))).Append('>');
            }

            builder.AppendLine().Append(' ', indentation).AppendLine("{");
            indentation += 4;
        }

        var modifiers  = declaration is MethodDeclarationSyntax methodDeclaration ? methodDeclaration.Modifiers : ((PropertyDeclarationSyntax)declaration).Modifiers;
        var returnType = member is IMethodSymbol method ? method.ReturnType : ((IPropertySymbol)member).Type;
        builder.Append(' ', indentation).Append(string.Join(" ", modifiers.Select(modifier => modifier.Text)));
        builder.Append(' ').Append(returnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append(" @").Append(member.Name);

        if (member is IMethodSymbol methodSymbol)
        {
            builder.Append('(');
            for (var index = 0; index < methodSymbol.Parameters.Length; index++)
            {
                if (index != 0)
                {
                    builder.Append(", ");
                }

                var parameter = methodSymbol.Parameters[index];
                var syntax    = (ParameterSyntax)parameter.DeclaringSyntaxReferences.Single().GetSyntax();
                if (syntax.Modifiers.Any(SyntaxKind.ScopedKeyword))
                {
                    builder.Append("scoped ");
                }

                if (parameter.RefKind == RefKind.Out)
                {
                    builder.Append("out ");
                }

                builder.Append(parameter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append(" @").Append(parameter.Name);
            }

            builder.Append(')');
        }

        var isTimeSpanValue = signature.AnchorKind == DurationValueKind.None && signature.ValueKind == DurationValueKind.TimeSpan;
        builder.Append(" => new global::").Append(isTimeSpanValue ? "System.TimeSpan(" : "Caprine.Durations.CalendarDuration(");
        if (!isTimeSpanValue)
        {
            builder.Append(duration.Years.ToString(CultureInfo.InvariantCulture)).Append(", ");
            builder.Append(duration.Months.ToString(CultureInfo.InvariantCulture)).Append(", ");
        }

        builder.Append(duration.FixedTicks.ToString(CultureInfo.InvariantCulture)).Append("L)");
        if (signature.AnchorKind != DurationValueKind.None)
        {
            var parameters = ((IMethodSymbol)member).Parameters;
            builder.Append('.').Append(signature.RuntimeMethod).Append('(');
            builder.Append(string.Join(", ", parameters.Select(parameter => (parameter.RefKind == RefKind.Out ? "out " : "") + "@" + parameter.Name)));
            builder.Append(')');
        }

        builder.AppendLine(";");
        for (var index = 0; index < containers.Count; index++)
        {
            indentation -= 4;
            builder.Append(' ', indentation).AppendLine("}");
        }

        if (namespaces.Count != 0)
        {
            builder.AppendLine("}");
        }

        return builder.ToString();
    }
}
